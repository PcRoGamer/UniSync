/**
 * Shared subtitle timing utilities for the Library's Karaoke & Transcript
 * components. Extracted from library/page.tsx so both the browsing view
 * and the dedicated [id] theatre page can import them without duplication.
 */

export type WordTiming = {
  text: string;
  start: number;
  end: number;
};

export type SegmentTiming = {
  start: number;
  end: number;
  text: string;
  words: WordTiming[];
};

/** Convert a VTT timestamp string (mm:ss.mmm or hh:mm:ss.mmm) to seconds. */
export function parseVttTimestamp(ts: string): number {
  const clean = ts.split(" ")[0].trim();
  const parts = clean.split(":").map(parseFloat);
  if (parts.length === 3) {
    return parts[0] * 3600 + parts[1] * 60 + parts[2];
  } else if (parts.length === 2) {
    return parts[0] * 60 + parts[1];
  }
  return parseFloat(clean) || 0;
}

/**
 * Parses raw WebVTT text (with inline <mm:ss.mmm> word tags or plain cues)
 * into structured segment and word timing structures for real-time
 * word-by-word highlighting (karaoke).
 *
 * Handles:
 * 1. Inline word timestamps (<00:12.345>word) generated by Whisper verbose_json.
 * 2. Multi-line cues within the same timing block.
 * 3. Plain subtitle cues without inline word markers by estimating even token durations.
 * 4. Stripping of WebVTT styling/speaker tags like <v Speaker 1>.
 */
export function parseVttToSegments(vttText: string): SegmentTiming[] {
  const lines = vttText.split(/\r?\n/);
  const segments: SegmentTiming[] = [];
  let currentStart = 0;
  let currentEnd = 0;
  let inCue = false;
  let cueTextLines: string[] = [];

  const finalizeCurrentCue = () => {
    if (!inCue || currentEnd <= currentStart || cueTextLines.length === 0) {
      cueTextLines = [];
      inCue = false;
      return;
    }

    const fullCueText = cueTextLines.join(" ").trim();
    if (!fullCueText) {
      cueTextLines = [];
      inCue = false;
      return;
    }

    const words: WordTiming[] = [];
    const wordRegex =
      /<(\d{1,2}:\d{2}(?:\.\d{3})?|\d{1,2}:\d{2}:\d{2}(?:\.\d{3})?)>([^<]+)/g;
    let match: RegExpExecArray | null;
    let accumulatedText = "";

    while ((match = wordRegex.exec(fullCueText)) !== null) {
      const wTime = parseVttTimestamp(match[1]);
      // Strip speaker tags or extra formatting if present
      const cleanWord = match[2].replace(/<[^>]+>/g, "").trim();
      if (cleanWord) {
        words.push({ text: cleanWord, start: wTime, end: wTime + 0.35 });
        accumulatedText += (accumulatedText ? " " : "") + cleanWord;
      }
    }

    if (words.length > 0) {
      // Connect each word's end boundary to the subsequent word's start
      for (let wIdx = 0; wIdx < words.length - 1; wIdx++) {
        words[wIdx].end = words[wIdx + 1].start;
      }
      words[words.length - 1].end = currentEnd;
      segments.push({
        start: currentStart,
        end: currentEnd,
        text: accumulatedText || fullCueText.replace(/<[^>]+>/g, "").trim(),
        words,
      });
    } else {
      // Plain cue without inline word tags: evenly distribute across the duration
      const cleanText = fullCueText.replace(/<[^>]+>/g, "").trim();
      if (cleanText) {
        const tokens = cleanText.split(/\s+/).filter(Boolean);
        const dur = Math.max(0.1, currentEnd - currentStart);
        const tokenWords = tokens.map((tok, idx) => ({
          text: tok,
          start: currentStart + (dur * idx) / tokens.length,
          end: currentStart + (dur * (idx + 1)) / tokens.length,
        }));
        segments.push({
          start: currentStart,
          end: currentEnd,
          text: cleanText,
          words: tokenWords,
        });
      }
    }

    cueTextLines = [];
    inCue = false;
  };

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i].trim();

    if (!line || line.startsWith("WEBVTT") || line.startsWith("NOTE")) {
      finalizeCurrentCue();
      continue;
    }

    if (line.includes("-->")) {
      finalizeCurrentCue();
      const parts = line.split("-->").map((p) => p.trim());
      if (parts.length === 2) {
        currentStart = parseVttTimestamp(parts[0]);
        currentEnd = parseVttTimestamp(parts[1]);
        inCue = true;
      }
      continue;
    }

    if (inCue && currentEnd > currentStart) {
      cueTextLines.push(line);
    }
  }

  // Handle trailing cue if file doesn't end with newline
  finalizeCurrentCue();

  return segments;
}

/** Format seconds into mm:ss display string. */
export function formatTimestamp(seconds: number): string {
  if (isNaN(seconds) || seconds < 0) return "00:00";
  const m = Math.floor(seconds / 60);
  const s = Math.floor(seconds % 60);
  return `${m.toString().padStart(2, "0")}:${s.toString().padStart(2, "0")}`;
}
